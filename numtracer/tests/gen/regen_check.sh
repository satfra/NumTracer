#!/usr/bin/env bash
# regen_check.sh — the codegen test that the rest of `ctest` is NOT.
#
# Every other test compiles the PRE-GENERATED headers in tests/gen/ and runs them; Wolfram is never
# invoked. So a green suite says nothing about a change to numtracer/mathematica/. This script
# REGENERATES the kernels from source, rebuilds, and re-runs the flow tests.
#
#   tests/gen/regen_check.sh [flow ...]   regenerate (default: the numeric flows below), rebuild, test
#   tests/gen/regen_check.sh --ctest      as above, but restore tests/gen/ on success (used by ctest)
#   tests/gen/regen_check.sh --restore    discard regenerated kernels, back to HEAD
#   tests/gen/regen_check.sh --record     regenerate, then WRITE diagram_counts.txt from the logs
#   tests/gen/regen_check.sh --with-form  ALSO regenerate the FORM oracles (slow; see FORM_FLOWS)
#
# Wired into ctest as the `codegen`-labelled test `codegen_regen`:
#   cmake -B build -DNUMTRACER_TEST_CODEGEN=ON && ctest --test-dir build -L codegen
# It re-invokes ctest with `-LE codegen` so it cannot recurse into itself.
#
# Reading a failure:
#   this fails but plain ctest passes -> your codegen change altered the emitted kernel.
#   both fail                         -> the committed artifacts are stale, not necessarily wrong.
#                                        See tests/gen/README.md.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
GEN="$REPO/numtracer/tests/gen"
BUILD="${NT_BUILD_DIR:-$REPO/numtracer/build}"

# Restore ONLY the generated artifacts (*.hh). This directory also holds 50+ tracked SOURCE files —
# the .wls generators, the .m fixtures, this script, README.md — and a blanket
# `git checkout -- numtracer/tests/gen/` reverted those too, silently discarding source edits made
# during a run. That is not hypothetical: it wiped a newly added assertion out of
# gen_multiterm_proj_numeric.wls and left the previously generated header on disk, so the very next
# codegen run passed while testing a kernel its generator no longer produced — a FALSE GREEN. It also
# ate this script's own DEFAULT_FLOWS edits three times. Regenerated kernels are the only thing that
# needs reverting; sources must survive.
restore() { git -C "$REPO" checkout -- 'numtracer/tests/gen/*.hh' 2>/dev/null; }

CTEST_MODE=0
RECORD=0
WITH_FORM=0
case "${1:-}" in
  --restore) restore; echo "restored tests/gen/ to HEAD"; exit 0 ;;
  --ctest)   CTEST_MODE=1; shift ;;
  --record)  RECORD=1; shift ;;
  --with-form) WITH_FORM=1; shift ;;
esac

# Run-time opt-in for the ctest wrapper. Exit 77 is the test's SKIP_RETURN_CODE (see CMakeLists.txt),
# so a plain `ctest` reports this Skipped in 0 s instead of launching a tens-of-minutes regeneration.
# Only --ctest consults it; invoking this script directly always runs.
if (( CTEST_MODE )) && [[ -z "${NT_RUN_CODEGEN:-}" ]]; then
  echo "codegen gate not requested (set NT_RUN_CODEGEN=1 to run the Wolfram regeneration)"
  exit 77
fi

# The FORM oracles. NOT regenerated by default — they are slow (minutes to ~107 min for aqbq147) and
# they are the INDEPENDENT side, so freezing them is the point.
#
# But independence lives in the TRACE ENGINE (FORM's algebra vs NumTracer's), NOT in the diagram
# enumeration. Both sides read the same *input specification* — symmetry lists, basis, projector — so
# when that specification changes, a frozen oracle is not independent, it is simply describing a
# different problem. That is not hypothetical: adding `FMakeSymmetryList` to the numeric generators
# and leaving these frozen failed flow_za3_num / flow_za4_num / flow_za3_147_form on the
# ANGLE-INTEGRATED (routing-invariant, physical) check by 58% / 4.5% / 2.5%, and regenerating the
# oracle made it green again with nothing else changed.
#
# So: if you edit what a flow COMPUTES, regenerate its oracle too — `--with-form`.
FORM_FLOWS=(
  gen_qcd_za3_form gen_qcd_za4_form gen_qcd_za3_147_form gen_zacbc_form
  gen_qcd_etapil_form gen_qcd_za_form gen_qcd_zq_form gen_qcd_zaqbq1_form
  gen_glu_quark_form gen_pion_quark_form gen_flavour_split_form
  gen_ym_za4_form
  # deliberately NOT here: gen_qcd_aqbq147_form (~107 min before the symmetry lists) — add explicitly.
)
# NB these write to tests/refshim/*.hh, NOT tests/gen/*.hh, so `restore()` above does not revert them
# and neither does the --ctest dirty guard. That is consistent (--ctest and --with-form are mutually
# exclusive, so the ctest gate never produces one), but it does mean a --with-form regeneration must
# be reviewed and committed by hand.

# Every NumTracer-generated kernel a test compares. `gen_zq_collect` emits a NumTracer kernel too
# (the collected Zq path, via MakeNTKernel) even though its name does not end in `_numeric` — leaving
# it out silently left one stale kernel behind and failed flow_zq_collect.
DEFAULT_FLOWS=(
  gen_qcd_za3_numeric gen_qcd_za4_numeric gen_zaqbq1_numeric gen_zq_numeric
  gen_qcd_za_numeric gen_qcd_za3_147_numeric gen_qcd_za4_147_numeric
  gen_qcd_aqbq147_numeric gen_ym_zacbc_numeric gen_qcd_etapil_numeric
  gen_zq_collect
  # gen_ym_za4_numeric was MISSING here while its generator carried an uncommitted FMakeSymmetryList
  # change, so flow_ym_za4_num passed only because BOTH its sides were frozen pre-symmetry — the exact
  # blind spot that let the original 6183-vs-294 bug live for weeks. Its FORM twin is in FORM_FLOWS.
  gen_ym_za4_numeric
  # Hand-built (no FunKit) DSL gates, cheap. The ONLY flow covering (a) an eager multi-term Dirac Plus
  # of mixed gamma parity — the physics flows above all have a well-defined diagram-global parity, so
  # they are blind to it; (b) the Power parity fold (sp[p2,p3]^2 must not recurse); (c) a COLLAPSED
  # all-delta spinor loop keeping its tr(1)=4 (a 0.25 ratio in compare_multiterm_proj_num means that
  # regressed). Emits two kernels: Multiterm_proj_num_kernel and Deltaloop_num_kernel.
  gen_multiterm_proj_numeric
  # Projector orthonormality on a REAL basis (AqbqDirect147) through the full pipeline.
  gen_ortho_numeric
  # FIXED Lorentz components (gamma^0, the finite-T 3+1 split). Hand-built, cheap. Was registered as
  # a ctest but NOT here, so the codegen suite — the only one that re-runs the generators — was blind
  # to it: a mathematica/ change could break this generator and every test would still pass.
  gen_fixedcomp_numeric
  # Four-quark Fierz orthonormality on a REAL basis (FierzCompleteNf2Nc3NJL). ~30 s. The only flow
  # here with TWO independent spinor lines, and the only one exercising the SU(N) Levi-Civita
  # contraction (colour AND flavour) on physics input — including a pair straddling an eager Plus.
  gen_fierz_ortho_numeric
  # The __host__ __device__ twins of ZA3/ZA4, consumed by the GPU/Kokkos integrate tests. These MUST
  # be regenerated in the same run as gen_qcd_za{3,4}_numeric above: ref_za3.cpp/ref_za4.cpp evaluate
  # the *_num* kernel in long double as the oracle for the *_gpu* kernel, so regenerating one side and
  # not the other is pure generation SKEW and turns the integrate gate red (measured: za3 3.7e-02,
  # za4 14.6) with nothing actually wrong. Leaving them out of this list is what let that happen.
  gen_qcd_za3_gpu gen_qcd_za4_gpu
  # The dense sub-term-dedup flow. Emits TWO kernels in one run (dedup ON, and a dedup-OFF control);
  # compare_zaaqbq1_small grades one against the other. The slowest flow here (~90 s), almost all of
  # it the dedup-OFF control — which is the speedup being tested.
  gen_zaaqbq1_small_numeric
  # The polyFrameSpec / unit-group / sign-canon fixture, and the ONLY flow whose emitted GENERATOR
  # SOURCES are tracked, not just its kernels: tests/gen/lambda3d{,_ref}/ commit gen_*.cpp, the eight
  # _u*.cpp units and probe_lambda3d_small_num.cpp. It was MISSING here while flow_lambda3d_small is
  # a registered ctest, so a codegen change could rewrite what those sources should be and nothing
  # would ever regenerate them to notice — the same blind spot gen_fixedcomp_numeric had above, but
  # worse, because `restore()` only reverts *.hh and would not revert those .cpp either. It also
  # means a byte-identity check must be `git status --porcelain -- numtracer/tests/gen` over the
  # whole subtree, NOT a *.hh glob. Emits two kernels (main + the all-levers-off control).
  gen_lambda3d_small_numeric
  # ---- the rest of the blind spot -------------------------------------------------------------
  # Every one of these emits a committed kernel that a REGISTERED ctest compiles and grades, and not
  # one of them was regenerated by this script. That is the gen_fixedcomp_numeric hole again, nine
  # times over: the tests were green because BOTH sides were frozen, so a codegen change could alter
  # what these kernels should be and the suite would never say so. Verified 2026-08-10 by diffing the
  # generator set against DEFAULT_FLOWS+FORM_FLOWS; each owns kernels no other generator writes.
  #
  # gen_flavour_ingroup and gen_gluon_condensate matter beyond that: they are the ONLY flows that
  # reach diagColPolys (the group-diagonal SU(N) dressing fold, which shells out to a helper binary),
  # so without them that whole code path had no regeneration coverage at all.
  # The COMPLEX x MULTI-TRACE intersection. gen_discdirac_numeric below is multi-trace but REAL, so
  # MakeNTKernel emits one body for it and neither real projection is ever built; every complex flow
  # in this list is LINEAR in its trace tokens. This is the only flow with both, i.e. the only one
  # that regenerates ntRePartIntegrand/ntPureIntegrand on a token polynomial rather than a linear
  # form. Cheap (~15 s, hand-built DSL, no FunKit).
  gen_cplxdisc_numeric
  # FINITE DENSITY: a Complex under a NEGATIVE POWER, i.e. 1/(l0 + I*muq + Ep)^2 — the only flow whose
  # coefficient the re/imaginary split cannot read off, and where getting it wrong is SILENT (Coefficient
  # power-series expands the rational function and returns the leading term, deleting muq). Regenerates
  # ntSplitRealImag's deferral path and the type-generic powr. Emits TWO kernels: the ordinary one and a
  # "RealOutput" -> True twin with the untouched complex body dropped, which is also the only coverage
  # of what RealOutput does at verdict 0 (this flow probes complex, by construction). Cheap (~30 s).
  gen_cplxrt_numeric
  gen_discdirac_numeric gen_flavour_ingroup gen_flavour_split gen_ftproj_numeric
  gen_glu_quark gen_gluon_condensate gen_pion_quark gen_proj_numeric gen_sigl_dirac
  # A FUNDAMENTAL flavour index with NO flavour generators — the third case none of the flavour
  # flows above covers: gen_pion_quark carries generators, gen_flavour_ingroup spells the engine
  # head itself, gen_flavour_split is flavour-blind, and gen_glu_quark's flavour line CLOSES to Nf.
  # Here the tadpole's quartic makes the deltas a WEB that no rewrite rule can close, so this is the
  # only flow exercising promoteFlavResidue. Emits TWO kernels (the plain deltaFundFlav spelling and
  # the Sqrt[2 Nf] TFlav[0,..] spelling of the same object); compare_kaon_tadpole grades one against
  # the other. Cheap (scalar-only theory, no Dirac, no colour).
  gen_kaon_tadpole
  # The finite-T ELECTRIC/MAGNETIC VERTEX SPLIT gate (ctest emvertex_num). Three projectors on three
  # DIFFERENT external momenta through a shared three-index core — the structure arXiv:1708.03482
  # App. B puts under the gluonic vertices, and the front-end path SP_EM depends on. gen_ftproj_numeric
  # above does NOT cover it: there both projectors sit on the same momentum. Emits four kernels
  # (a non-zero control plus the two zero-identities).
  gen_emvertex_numeric
  # The finite-T SPATIAL VECTOR gate (ctest spatialvec_num): FormTracer's `vecs[q,mu]` and the
  # spatial pslash, routed through the ntSpatialVec momentum leaf. gen_ftproj_numeric above covers
  # only the SCALAR spatial product ntSPS, which never reaches the engine — it folds into the
  # coefficient — so nothing there exercises a spatial momentum going through a Dirac trace. Emits
  # three kernels (two non-zero oracle checks plus the ntSPS-vs-leaf zero identity).
  gen_spatialvec_numeric
)
FLOWS=("$@")
[[ ${#FLOWS[@]} -eq 0 ]] && FLOWS=("${DEFAULT_FLOWS[@]}")
# FORM oracles run FIRST so the numeric side is graded against an oracle built from the same spec.
(( WITH_FORM )) && FLOWS=("${FORM_FLOWS[@]}" "${FLOWS[@]}")

WOLFRAM="$(command -v wolfram || command -v wolframscript || true)"
[[ -n "$WOLFRAM" ]] || { echo "ERROR: no Wolfram kernel on PATH"; exit 1; }
[[ -d "$BUILD" ]]   || { echo "ERROR: build dir not found: $BUILD"; exit 1; }

# --ctest mode ends by running restore(), i.e. `git checkout -- numtracer/tests/gen/*.hh`. If the
# tree already holds an UNCOMMITTED regeneration, that silently throws it away — and a regeneration
# is often exactly the deliverable someone is in the middle of producing. Refuse rather than destroy;
# plain mode (no flag) never restores and is the right tool when the kernels are the product.
if (( CTEST_MODE )); then
  dirty=$(git -C "$REPO" status --porcelain -- 'numtracer/tests/gen/*.hh' 2>/dev/null | wc -l)
  if (( dirty > 0 )); then
    echo "ERROR: $dirty regenerated kernel(s) in tests/gen/ are uncommitted."
    echo "       --ctest finishes by discarding them (git checkout). Refusing so your regeneration survives."
    echo "       Commit/stash them first, or run '$0' with no flag (never restores)."
    exit 1
  fi
fi

# The density guard below greps the generator's "[cse] sub-terms:" line, which NumTracer emits through
# ntLog — silent unless $NumTracerVerbose. Codegen.m turns that flag on when NT_GEN_VERBOSE is set, so
# enable it here (harmless extra [time]/[prof] lines in the other flows' logs).
export NT_GEN_VERBOSE=1

# Did this flow's generation ACTUALLY happen? The exit code alone cannot say: `wolfram -script`
# returns 0 even when MakeNTKernel hits Abort[], and when it does the build below silently links the
# STALE committed kernels and every flow test passes — a FALSE GREEN that has fired twice for real
# (2026-07-19: 170 `::string` errors, no generator written, gate green in 271 s; and again when the
# emitted C++ failed to COMPILE, where `wrote generator` IS present so a guard keyed on it passes).
#
# There are two independent modes, so check both:
#   1. Codegen.m aborted before emitting  -> no `wrote generator:`, and `::string`/`cppleak` present.
#   2. Codegen.m emitted but the generator failed to build/run -> `MakeNTKernel::genfail`.
# `genfail == 0` is the reliable signal. `wrote kernel:` is NOT required — the plain MakeNTKernel test
# flows legitimately never print it (only the MakeNTKernel/DiFfRG path does), so demanding it would
# fail honest flows; `wrote generator:` is the marker every numeric flow emits.
check_flow_log() {
  local f=$1 log=$2 bad=0 n
  # 0. the package did not load. A syntax error in mathematica/*.m is a SILENT no-op in Mathematica
  #    (Get returns Null, definitions after the malformed expression are simply absent), so the flow
  #    runs on a half-defined package and fails far downstream in a way that names the wrong thing:
  #    measured, an unbalanced bracket mid-Codegen.m surfaced only as
  #    `SetOptions::optnf: RuntimeInclude is not a known option for MakeNTKernel` plus a 0.0001 s
  #    numeric backend, and cost a long detour before anyone looked upward in the log. NumTracer.m
  #    now aborts on it (NumTrace::loadsyntax), but `wolfram -script` still exits 0 on Abort[] — same
  #    reason the checks below exist — so it has to be caught here too. Checked FIRST: when this
  #    fires, every other symptom in the log is downstream noise.
  n=$(grep -acE 'Syntax::|loadsyntax' "$log" 2>/dev/null || true)
  (( n == 0 )) || { echo "      Syntax::/loadsyntax x$n — numtracer/mathematica/ FAILED TO PARSE; fix that first, the rest of this log is noise"; bad=1; }
  n=$(grep -ac 'genfail' "$log" 2>/dev/null || true)
  (( n == 0 )) || { echo "      genfail x$n — the emitted generator failed to build/run"; bad=1; }
  n=$(grep -acE '::string|cppleak' "$log" 2>/dev/null || true)
  (( n == 0 )) || { echo "      ::string/cppleak x$n — Codegen.m aborted before emitting"; bad=1; }
  n=$(grep -ac 'wrote generator:' "$log" 2>/dev/null || true)
  (( n >= 1 )) || { echo "      no 'wrote generator:' — nothing was emitted for this flow"; bad=1; }
  return $bad
}

# ---- DIAGRAM-COUNT WATCHDOG ------------------------------------------------------------------
# Nothing in this repo watched how BIG a flow's input is, and that blindness cost a 21x self-inflicted
# slowdown: FunKit 0bacdd1 made FSymmetry lists manual, none of the tests/gen generators were updated,
# and za4_147 silently traced 6,183 diagrams instead of 294 for weeks. Every test stayed green — the
# physics was right, there was just 21x more of it. A diagram count is a discrete structural property
# of a flow, so freeze it and compare exactly; a legitimate change to a flow updates the table.
#
# A flow may run NumTrace more than once (gen_multiterm_proj / gen_zaaqbq1_small each emit two
# kernels), so the fingerprint is the comma-joined list of counts in log order.
COUNTS="$GEN/diagram_counts.txt"

flow_counts() { # $1 = log -> "294" or "12,4" or "" if the flow never logged one
  sed -n 's/.*\[prof\] NumTrace analyseDiagram (\([0-9]*\) diagrams).*/\1/p' "$1" | paste -sd, -
}

check_counts() {
  local bad=0 f log got want
  [[ -f "$COUNTS" ]] || { echo "  (no diagram_counts.txt yet — record one with: $0 --record)"; return 0; }
  echo "diagram-count watchdog:"
  for f in "${FLOWS[@]}"; do
    log="/tmp/regen_$f.log"
    [[ -f "$log" ]] || continue
    got=$(flow_counts "$log")
    [[ -n "$got" ]] || continue          # flow logs no count (not a NumTrace flow); nothing to check
    want=$(awk -v k="$f" '$1==k{print $2}' "$COUNTS")
    if [[ -z "$want" ]]; then
      printf '  %-28s %-16s (not in table — add it)\n' "$f" "$got"
    elif [[ "$got" == "$want" ]]; then
      printf '  %-28s %-16s ok\n' "$f" "$got"
    else
      printf '  %-28s %-16s MISMATCH (expected %s)\n' "$f" "$got" "$want"
      bad=1
    fi
  done
  if (( bad )); then
    echo
    echo "  FAIL: a flow's diagram count changed. This is the input-inflation guard:"
    echo "        a JUMP usually means lost FSymmetry/symmetry lists (see the 6183-vs-294 za4_147 bug),"
    echo "        a DROP usually means a basis or NT_TEST_NDIAG restriction crept in."
    echo "        If the change is intended, re-record: $0 --record"
    return 1
  fi
  return 0
}

echo "regenerating ${#FLOWS[@]} flow(s) from source ..."
fail=0
for f in "${FLOWS[@]}"; do
  [[ -f "$GEN/$f.wls" ]] || { echo "  SKIP $f (no such .wls)"; continue; }
  printf '  %-28s ' "$f"
  log="/tmp/regen_$f.log"
  if ! (cd "$GEN" && "$WOLFRAM" -script "$f.wls" >"$log" 2>&1); then
    echo "FAILED (see $log)"; fail=1; continue
  fi
  # exit code 0 is necessary but NOT sufficient — see check_flow_log above
  if check_flow_log "$f" "$log"; then
    echo "ok"
  else
    echo "  ^ SILENT GENERATION FAILURE (exit 0 but nothing emitted; see $log)"; fail=1
  fi
done
if (( fail )); then
  echo "generation failed; leaving tests/gen/ as-is for inspection (restore: $0 --restore)"
  exit 1
fi

if (( RECORD )); then
  : > "$COUNTS.new"
  {
    echo "# Frozen diagram counts per flow — the input-inflation watchdog (see regen_check.sh)."
    echo "# One line per flow: <generator>  <comma-joined NumTrace diagram counts, in log order>."
    echo "# Re-record with: tests/gen/regen_check.sh --record"
  } >> "$COUNTS.new"
  for f in "${FLOWS[@]}"; do
    log="/tmp/regen_$f.log"
    [[ -f "$log" ]] || continue
    c=$(flow_counts "$log")
    [[ -n "$c" ]] && printf '%s\t%s\n' "$f" "$c" >> "$COUNTS.new"
  done
  mv "$COUNTS.new" "$COUNTS"
  echo "recorded $(grep -vc '^#' "$COUNTS") flow counts -> ${COUNTS#"$REPO/"}"
fi

if ! check_counts; then
  echo "tests/gen/ left as-is for inspection; restore with: $0 --restore"
  exit 1
fi

# DENSITY GUARD for the sub-term-dedup flow. compare_zaaqbq1_small grades the dedup-ON kernel against
# a dedup-OFF control — but if the flow ever loses its sub-term density (a setup edit that lets the
# {[g,g],g} structure sigma-fold, a basis restricted to the wrong element, NT_TEST_NDIAG cut too far),
# the two kernels become the SAME trivial computation and the test passes while checking nothing. Every
# other flow in tests/gen is already in exactly that state — 1 sub-term per net — which is why this
# flow exists. So assert the density the flow is supposed to have, from the generator's own log.
log=/tmp/regen_gen_zaaqbq1_small_numeric.log
if [[ -f "$log" ]]; then
  line=$(grep -m1 '\[cse\] sub-terms:' "$log" || true)
  redun=$(sed -n 's/.*distinct traces (\([0-9.]*\)x).*/\1/p' <<<"$line")
  fold=$(sed -n 's/.*(longest \([0-9]*\)).*/\1/p' <<<"$line")
  echo "  density guard: ${line#*\[cse\] }"
  if [[ -z "$redun" || -z "$fold" ]] \
     || ! awk -v r="$redun" 'BEGIN{exit !(r > 2.0)}' \
     || (( fold < 10 )); then
    echo "  FAIL: the dense flow lost its sub-term density (need redundancy > 2x and longest fold >= 10)."
    echo "        It is the ONLY flow that exercises the dedup; without it the suite is blind to it."
    exit 1
  fi
fi

echo "rebuilding against the regenerated kernels ..."
if ! cmake --build "$BUILD" -j "$(nproc)" >/tmp/regen_build.log 2>&1; then
  echo "ERROR: build failed (see /tmp/regen_build.log)"; exit 1
fi

echo "running the flow tests against the REGENERATED kernels ..."
# -LE codegen: never re-enter this test (it is itself a ctest when NUMTRACER_TEST_CODEGEN=ON)
if ctest --test-dir "$BUILD" -LE codegen --output-on-failure; then
  echo
  echo "PASS — codegen reproduces kernels that still match the oracles."
  if (( CTEST_MODE )); then
    restore
    # the test binaries now embed the regenerated kernels; rebuild so the tree is left consistent
    cmake --build "$BUILD" -j "$(nproc)" >/dev/null 2>&1
    echo "(restored tests/gen/ to HEAD)"
  fi
  exit 0
else
  echo
  echo "FAIL — the regenerated kernels differ from the frozen oracles."
  echo "Before blaming Codegen.m, check whether the ORACLE is the stale side:"
  echo "  * the refshim FORM oracles are frozen MANUAL copies of flows/<NAME>/kernel.hh (README.md)"
  echo "  * a FunKit backend/routing change moves the integrand without changing the physics"
  echo "    (FUNKIT_ROUTING_ISSUE.md at the repo root)"
  echo "tests/gen/ left as-is for inspection; restore with: $0 --restore"
  exit 1
fi
